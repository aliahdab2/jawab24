/* eslint-disable @typescript-eslint/no-require-imports */
/**
 * App Store Guideline 3.1.1 — remove every payment surface from the iOS bundle.
 *
 * Run after `build:mobile` and before `cap sync ios`. iOS ONLY: the same `out/`
 * feeds the Android build, where these routes are legitimate.
 *
 * WHY THIS EXISTS (2026-08-10). The pages already self-gate at runtime via
 * `useIOSPaymentRedirect`, but that guard is a REACT guard: it can only blank
 * the page once hydration has run. Next exports these routes as static HTML
 * built with `isIOSNative() === false`, so the shipped `pricing/scale.html`
 * contains the full plan grid — headline, feature list and "$US 149" — as
 * plain markup that renders with zero JavaScript. Anything that paints that
 * file before hydration shows a reviewer exactly what 3.1.1 forbids. This was
 * observed once on a simulator: the grid rendered for seconds after a deep
 * link, and was not reproducible afterwards — a race, which is precisely the
 * kind of defect a guard cannot close (AI_INSTRUCTIONS Rule 14, prevention
 * over detection).
 *
 * We REPLACE rather than DELETE. A missing file makes a hard navigation render
 * the WebView's error page; a stub always lands the user somewhere sane. The
 * stub carries no price, no plan name and no upgrade wording, so even if it is
 * painted it is 3.1.1-clean.
 *
 * Client-side navigation is unaffected: Next routes through the page's JS
 * chunk, not through this file, so the runtime guard still handles in-app
 * navigation. The two layers are complementary, not redundant.
 */
const fs = require('fs');
const path = require('path');

const outDir = path.join(__dirname, '..', 'out');

if (!fs.existsSync(outDir)) {
  console.error('out/ directory not found. Run build:mobile first.');
  process.exit(1);
}

/**
 * Every statically-exported route that can show a price, a plan or a purchase
 * action. Derived from the build output, not from the navigation: the whole
 * point is that these stay reachable when nothing links to them.
 */
const PAYMENT_ROUTES = [
  'pricing.html',
  'pricing/scale.html',
  'checkout.html',
  'payment/success.html',
  'payment/cancel.html',
  'payment/return.html',
];

/** Markers that must not survive in any shipped iOS HTML. */
const FORBIDDEN_MARKERS = ['$US', 'ر.س/شهر', 'باقات التوسّع'];

const stub = (route) => `<!DOCTYPE html>
<html><head><meta charset="utf-8">
<title>Jawab24</title>
<meta name="robots" content="noindex,nofollow">
<script>location.replace('/dashboard.html');</script>
</head><body></body></html>
<!-- ${route} is not available in the iOS build (App Store Guideline 3.1.1).
     Generated by scripts/neutralize-ios-payment-routes.js — do not edit. -->
`;

console.log('Neutralizing payment routes for the iOS bundle (Guideline 3.1.1)...');

let replaced = 0;
for (const route of PAYMENT_ROUTES) {
  const filePath = path.join(outDir, route);
  if (!fs.existsSync(filePath)) {
    // Not fatal: a route may legitimately disappear from the export. Loud, so a
    // renamed route cannot silently stop being neutralized.
    console.warn(`  ! ${route} not found in out/ — skipped (did the route move?)`);
    continue;
  }
  const before = Math.round(fs.statSync(filePath).size / 1024);
  fs.writeFileSync(filePath, stub(route));
  replaced += 1;
  console.log(`  Replaced ${route} (${before}KB -> stub)`);
}

if (replaced === 0) {
  console.error('No payment routes were neutralized — the route list is stale. Refusing to ship.');
  process.exit(1);
}

// Verify against the built output rather than trusting the list above: any
// remaining HTML carrying a price marker is a route we forgot.
const offenders = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === '_next') continue; // JS chunks are gated at runtime, not markup
      walk(full);
    } else if (entry.name.endsWith('.html')) {
      // Scan RENDERED markup only. Next serializes the whole next-intl message
      // catalogue into __NEXT_DATA__, so the pricing strings ("ر.س/شهر" and
      // friends) legitimately appear as JSON inside a <script> on every page.
      // That is data, not a payment surface — it never paints, and 3.1.1 is
      // about what the user can see and buy. Scanning raw HTML flags all 13
      // dashboard pages and hides the real signal.
      const markup = fs
        .readFileSync(full, 'utf8')
        .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
      const hit = FORBIDDEN_MARKERS.find((m) => markup.includes(m));
      if (hit) offenders.push(`${path.relative(outDir, full)} (contains "${hit}")`);
    }
  }
};
walk(outDir);

if (offenders.length > 0) {
  console.error('Payment markup still present in the iOS bundle:');
  for (const o of offenders) console.error(`  - ${o}`);
  console.error('Add the route to PAYMENT_ROUTES above. Refusing to ship a 3.1.1 violation.');
  process.exit(1);
}

console.log(`Neutralized ${replaced} payment routes; no price markup remains in any iOS HTML.`);
